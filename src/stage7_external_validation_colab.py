# Helper: Run 3-model consensus on any set of SMILES
# =====================================================================
def run_consensus(smiles_list, catboost_model, rf_model, chemprop_model,
                  smiles_col_source='canonical_smiles'):
    """
    Run CatBoost, RF, and Chemprop predictions on a list of SMILES.
    Returns DataFrame with columns: smiles, p_catboost, p_rf, p_chemprop, p_consensus, model_variance
    """
    N_BITS, RADIUS, DTYPE = 4096, 3, np.uint16

    # --- Generate ECFP6 features ---
    rows, cols, vals = [], [], []
    valid_indices = []
    for i, smi in enumerate(smiles_list):
        mol = Chem.MolFromSmiles(str(smi))
        if mol is None:
            continue
        fp = AllChem.GetHashedMorganFingerprint(mol, radius=RADIUS, nBits=N_BITS)
        arr = np.zeros(N_BITS, dtype=DTYPE)
        for bit, count in fp.GetNonzeroElements().items():
            arr[bit] = min(count, 65535)
        valid_indices.append(i)
        nz = np.nonzero(arr)[0]
        rows.extend([len(valid_indices) - 1] * len(nz))
        cols.extend(nz.tolist())
        vals.extend(arr[nz].tolist())

    X = sp.coo_matrix(
        (np.array(vals, dtype=DTYPE),
         (np.array(rows, dtype=np.int32), np.array(cols, dtype=np.int32))),
        shape=(len(valid_indices), N_BITS), dtype=DTYPE
    ).tocsr().astype(np.float32)

    valid_smiles = [str(smiles_list[i]) for i in valid_indices]

    # --- CatBoost ---
    from catboost import Pool
    pool = Pool(X, feature_names=[f'ecfp6_bit_{i}' for i in range(X.shape[1])])
    p_catboost = catboost_model.predict_proba(pool)[:, 1]

    # --- Balanced RF ---
    p_rf = rf_model.predict_proba(X)[:, 1]

    # --- Chemprop D-MPNN ---
    from chemprop import data as cdata
    from chemprop.featurizers import SimpleMoleculeMolGraphFeaturizer
    import lightning

    mols = [Chem.MolFromSmiles(s) for s in valid_smiles]
    # All should parse (we filtered above), but double-check
    mols_clean = []
    smiles_clean = []
    for m, s in zip(mols, valid_smiles):
        if m is not None:
            mols_clean.append(m)
            smiles_clean.append(s)

    datapoints = [cdata.MoleculeDatapoint(mol=m, y=np.array([0.0], dtype=np.float32))
                  for m in mols_clean]
    featurizer = SimpleMoleculeMolGraphFeaturizer()
    dataset = cdata.MoleculeDataset(datapoints, featurizer)
    loader = cdata.build_dataloader(dataset, batch_size=64, shuffle=False)

    predict_trainer = lightning.Trainer(
        accelerator='gpu', devices=1, enable_progress_bar=False, logger=False
    )
    predictions_list = predict_trainer.predict(chemprop_model, loader)
    p_chemprop_valid = torch.cat([p.flatten() for p in predictions_list]).cpu().numpy()

    # Build result DataFrame
    result = pd.DataFrame({
        'smiles': smiles_clean,
        'p_catboost': p_catboost[:len(smiles_clean)],
        'p_rf': p_rf[:len(smiles_clean)],
        'p_chemprop': p_chemprop_valid[:len(smiles_clean)],
    })
    result['p_consensus'] = (
        result['p_chemprop'] + result['p_catboost'] + result['p_rf']
    ) / 3.0
    mean_p = result['p_consensus'].values
    result['model_variance'] = (
        (result['p_chemprop'].values - mean_p)**2 +
        (result['p_catboost'].values - mean_p)**2 +
        (result['p_rf'].values - mean_p)**2
    ) / 3.0

    return result


